color_for() {
  local v=$1
  if [ "$v" -ge 80 ] 2>/dev/null; then echo '\033[01;31m'
  elif [ "$v" -ge 50 ] 2>/dev/null; then echo '\033[01;33m'
  else echo '\033[01;32m'; fi
}

format_duration() {
  local s=$1
  if [ "$s" -lt 60 ]; then
    echo "${s}s"
  elif [ "$s" -lt 3600 ]; then
    echo "$((s / 60))m"
  else
    echo "$((s / 3600))h$(((s % 3600) / 60))m"
  fi
}

